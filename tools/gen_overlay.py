# Text layout on the 40x30 grid (8x8 px cells, 320x240 screen).
# Each entry: (row, col, item). An item is either a literal string or a
# (field, width) tuple rendered from live values:
#   ('hex', name)   two hex digits from an 8-bit signal
#   ('bcd5', name)  five decimal digits from a 20-bit BCD signal
#   ('mode', None)  six-char player mode name
#   ('onoff', name) "ON " / "OFF" from a 1-bit signal
LAYOUT = [
    (1, 2,  "DRAGON'S LAIR - LD-V1000 TEST CORE"),
    (3, 2,  "MODE"),   (3, 8, ('mode', None)),
    (3, 22, "STATUS"), (3, 29, ('hex', 'status')),
    (4, 2,  "LAST CMD"), (4, 11, ('hex', 'last_cmd')),
    (4, 22, "TARGET"), (4, 29, ('bcd5', 'target_bcd')),
    (5, 2,  "AUDIO L"), (5, 10, ('onoff', 'audio_l')),
    (5, 14, "R"), (5, 16, ('onoff', 'audio_r')),
    (5, 22, "CMDS"), (5, 29, ('hex', 'cmd_count')),
    (7, 15, "DISC FRAME"),
    (21, 2, "PLAYER 1"), (21, 22, "PLAYER 2"),
    (26, 2, "LIVES"), (26, 13, "CREDITS"), (26, 30, "LIVES"),
]

MODES = ["PARK  ", "PLAY  ", "SCAN F", "SCAN R", "SEARCH", "STILL "]


def write_font(path):
    lines = [
        "// Generated by tools/gen_overlay.py - do not edit by hand.",
        "// 5x7 glyphs placed in 8x8 cells. row 7 is always blank.",
        "`default_nettype none",
        "module dl_font (",
        "    input  wire [6:0] ch,",
        "    input  wire [2:0] row,",
        "    output reg  [4:0] bits   // bit 4 = leftmost pixel",
        ");",
        "always @(*) begin",
        "    bits = 5'b00000;",
        "    case ({ch, row})",
    ]
    for c, rows in sorted(GLYPHS.items()):
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), c
        code = ord(c)
        for r, pattern in enumerate(rows):
            v = int(pattern.replace('#', '1').replace(' ', '0'), 2)
            if v:
                lines.append(f"    {{7'd{code}, 3'd{r}}}: bits = 5'b{v:05b};  // '{c}'")
    lines += ["    default: bits = 5'b00000;", "    endcase", "end", "endmodule", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))


def write_text(path):
    used = set()
    cells = []  # (row, col, verilog_expr_for_char)
    for row, col, item in LAYOUT:
        if isinstance(item, str):
            for i, c in enumerate(item):
                if c != ' ':
                    assert c in GLYPHS, c
                    cells.append((row, col + i, f"7'd{ord(c)}"))
        else:
            kind, name = item
            if kind == 'hex':
                used.add(name)
                cells.append((row, col, f"hexch({name}[7:4])"))
                cells.append((row, col + 1, f"hexch({name}[3:0])"))
            elif kind == 'bcd5':
                used.add(name)
                for i in range(5):
                    hi = 19 - 4 * i
                    cells.append((row, col + i, f"hexch({name}[{hi}:{hi - 3}])"))
            elif kind == 'onoff':
                used.add(name)
                cells.append((row, col, "7'd79"))  # 'O'
                cells.append((row, col + 1, f"({name} ? 7'd78 : 7'd70)"))
                cells.append((row, col + 2, f"({name} ? 7'd32 : 7'd70)"))
            elif kind == 'mode':
                for i in range(6):
                    cells.append((row, col + i, f"modech({i})"))
    seen = {}
    for r, c, e in cells:
        assert (r, c) not in seen, f"overlap at row {r} col {c}"
        assert 0 <= c < 40 and 0 <= r < 30
        seen[(r, c)] = e

    lines = [
        "// Generated by tools/gen_overlay.py - do not edit by hand.",
        "// Maps a 40x30 text cell to an ASCII code using live player state.",
        "`default_nettype none",
        "module dl_text (",
        "    input  wire [4:0]  row,",
        "    input  wire [5:0]  col,",
        "    input  wire [2:0]  mode,",
        "    input  wire [7:0]  status,",
        "    input  wire [7:0]  last_cmd,",
        "    input  wire [7:0]  cmd_count,",
        "    input  wire [19:0] target_bcd,",
        "    input  wire        audio_l,",
        "    input  wire        audio_r,",
        "    output reg  [6:0]  ch",
        ");",
        "function [6:0] hexch(input [3:0] n);",
        "    hexch = (n < 4'd10) ? (7'd48 + {3'd0, n}) : (7'd55 + {3'd0, n});",
        "endfunction",
        "",
        "// six-character mode names",
        "function [6:0] modech(input integer i);",
        "    reg [47:0] s;",
        "    begin",
        "        case (mode)",
    ]
    for m, name in enumerate(MODES):
        hexs = "".join(f"{ord(c):02x}" for c in name)
        lines.append(f"            3'd{m}: s = 48'h{hexs};  // \"{name}\"")
    lines += [
        "            default: s = 48'h3f3f3f3f3f3f;",
        "        endcase",
        "        modech = s[46 - 8*i -: 7];",
        "    end",
        "endfunction",
        "",
        "always @(*) begin",
        "    ch = 7'd32;",
        "    case ({row, col})",
    ]
    for (r, c), e in sorted(seen.items()):
        lines.append(f"    {{5'd{r}, 6'd{c}}}: ch = {e};")
    lines += ["    default: ch = 7'd32;", "    endcase", "end", "endmodule", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    rtl = os.path.join(root, "src", "fpga", "rtl")
    write_font(os.path.join(rtl, "dl_font.v"))
    write_text(os.path.join(rtl, "dl_text.v"))
    print("wrote dl_font.v and dl_text.v")
